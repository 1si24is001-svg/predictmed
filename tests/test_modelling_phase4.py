def test_pytorch_mlp_fit_predict():
    from predictmed.models.candidates import make_candidate

    rng = np.random.default_rng(42)
    n = 120
    X = pd.DataFrame({
        "age": rng.integers(30, 85, n),
        "egfr": rng.uniform(15, 90, n),
        "sbp": rng.uniform(110, 180, n),
    })
    y = ((X["egfr"] < 45) | (X["sbp"] > 150)).astype(int)

    model = make_candidate("pytorch_mlp", seed=42)
    model.fit(X, y)
    probs = model.predict_proba(X)

    assert probs.shape == (n, 2)
    assert np.allclose(probs.sum(axis=1), 1.0)
    assert (probs >= 0.0).all() and (probs <= 1.0).all()


def test_discrete_time_survival_monotonicity():
    from predictmed.models.survival import DiscreteTimeSurvivalModel

    rng = np.random.default_rng(42)
    n = 100
    X = pd.DataFrame({
        "age": rng.integers(30, 85, n),
        "egfr": rng.uniform(15, 90, n),
    })
    # Realistic cumulative hazards: y12 <= y24 <= y36
    y12 = (X["egfr"] < 30).astype(int)
    y24 = (X["egfr"] < 45).astype(int)
    y36 = (X["egfr"] < 60).astype(int)

    surv = DiscreteTimeSurvivalModel(horizons=(12, 24, 36), random_state=42)
    surv.fit(X, {12: y12, 24: y24, 36: y36})

    cum_risk = surv.predict_cumulative_risk(X)
    assert cum_risk.shape == (n, 3)
    # Monotonicity check: cum_risk[:, 0] <= cum_risk[:, 1] <= cum_risk[:, 2]
    assert np.all(cum_risk[:, 0] <= cum_risk[:, 1] + 1e-9)
    assert np.all(cum_risk[:, 1] <= cum_risk[:, 2] + 1e-9)

    s = surv.predict_survival(X)
    assert np.allclose(s, 1.0 - cum_risk)


def test_conformal_tradeoff_table():
    from predictmed.models.uncertainty import conformal_tradeoff_table

    rng = np.random.default_rng(42)
    n_cal = 200
    cal_scores = rng.uniform(0.01, 0.99, n_cal)
    cal_labels = (cal_scores > 0.45).astype(int)

    n_test = 150
    test_scores = rng.uniform(0.01, 0.99, n_test)
    test_labels = (test_scores > 0.45).astype(int)

    table = conformal_tradeoff_table(cal_scores, cal_labels, test_scores, test_labels, alphas=(0.05, 0.10, 0.20))
    assert len(table) == 3
    for row in table:
        assert 0.0 <= row["empirical_coverage"] <= 1.0
        assert 0.0 <= row["uncertain_share"] <= 1.0
        assert 0.0 <= row["empty_share"] <= 1.0


def test_crash_dialysis_bootstrap_report():
    from predictmed.models.metrics import crash_dialysis_bootstrap_report

    rng = np.random.default_rng(42)
    n = 200
    y = np.zeros(n, dtype=int)
    y[rng.choice(n, size=15, replace=False)] = 1
    p = rng.uniform(0.01, 0.4, n)
    p[y == 1] += 0.3

    rep = crash_dialysis_bootstrap_report(y, p, n_boot=50, seed=42)
    assert rep["status"] == "EXPLORATORY"
    assert "caveat" in rep
    assert rep["n_events"] == 15
    assert not np.isnan(rep["auroc"])
    assert len(rep["auroc_95ci"]) == 2


def test_llm_narration_mocked_anthropic():
    from predictmed.agents.care_navigator import CareNavigator, DISCLAIMER
    from predictmed.agents.core import Journal, LLM

    mock_client = MagicMock()
    mock_msg = MagicMock()
    mock_block = MagicMock()
    mock_block.type = "text"
    mock_block.text = "This is a synthetic outreach brief generated by Claude for testing."
    mock_msg.content = [mock_block]
    mock_client.messages.create.return_value = mock_msg

    with patch.dict(os.environ, {"ANTHROPIC_API_KEY": "fake_test_key", "PREDICTMED_LLM_MODEL": "claude-3-opus-custom"}):
        llm = LLM(cfg={"default_model": "claude-sonnet-4-5"})
        llm._client = mock_client
        agent = CareNavigator(journal=Journal(), llm=llm)

        row = {
            "member_id": "M-TEST-123",
            "p_deterioration": 0.42,
            "va_low": 0.30,
            "va_high": 0.55,
            "twin_runway_months": 18,
            "care_gaps": "NO_RASI|NO_UACR_TEST",
        }

        brief = agent.brief(row)

        # 1. Model configuration is honored
        assert llm.model == "claude-3-opus-custom"
        assert mock_client.messages.create.called
        call_kwargs = mock_client.messages.create.call_args[1]
        assert call_kwargs["model"] == "claude-3-opus-custom"

        # 2. Safety invariants: member_id and actions are strictly deterministic
        assert brief["member_id"] == "M-TEST-123"
        assert len(brief["actions"]) == 2
        assert brief["actions"][0]["gap"] == "NO_RASI"
        assert brief["actions"][1]["gap"] == "NO_UACR_TEST"
        # 3. Disclaimer is strictly preserved
        assert DISCLAIMER in brief["text"]
        assert brief["disclaimer"] == DISCLAIMER


def test_llm_narration_fallback_on_exception():
    from predictmed.agents.care_navigator import CareNavigator, DISCLAIMER
    from predictmed.agents.core import Journal, LLM

    mock_client = MagicMock()
    mock_client.messages.create.side_effect = RuntimeError("API connection timeout")

    with patch.dict(os.environ, {"ANTHROPIC_API_KEY": "fake_test_key"}):
        llm = LLM()
        llm._client = mock_client
        agent = CareNavigator(journal=Journal(), llm=llm)

        row = {
            "member_id": "M-ERR-999",
            "p_deterioration": 0.35,
            "care_gaps": "NO_UACR_TEST",
        }

        brief = agent.brief(row)
        assert brief["member_id"] == "M-ERR-999"
        assert "Member M-ERR-999" in brief["text"]
        assert DISCLAIMER in brief["text"]
